def sample_scenario_seeds(category_slug, n, rng=None):
    """Return n distinct, concrete scenario strings mixing topic+tone+structure."""
    rng = rng or random
    topics = TOPICS.get(category_slug, TOPICS["everyday"])
    seeds = []
    used_combo = set()
    attempts = 0
    while len(seeds) < n and attempts < n * 20:
        attempts += 1
        topic = rng.choice(topics)
        tone = rng.choice(TONES)
        shape = rng.choice(STRUCTURE_SHAPES)
        key = (topic, tone, shape)
        if key in used_combo:
            continue
        used_combo.add(key)
        seeds.append(f"נושא: {topic} | טון: {tone} | מבנה: {shape}")
    return seeds
